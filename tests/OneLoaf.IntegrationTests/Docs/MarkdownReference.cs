using System.Globalization;
using System.Text;
using System.Text.Json;
using System.Text.Json.Nodes;

namespace OneLoaf.IntegrationTests.Docs;

/// <summary>Renders the Markdown reference of one service from its OpenAPI document and the recorded examples.</summary>
public sealed class MarkdownReference(string service, string title, string baseUrls, JsonNode spec, IReadOnlyDictionary<string, List<RecordedExchange>> examples)
{
    private const int MaxArrayItems = 2;
    private static readonly string[] Methods = ["get", "post", "put", "patch", "delete"];
    private static readonly JsonSerializerOptions Indented = new()
    {
        WriteIndented = true,
        Encoder = System.Text.Encodings.Web.JavaScriptEncoder.UnsafeRelaxedJsonEscaping,
    };

    private static readonly Dictionary<string, string> StatusMeaning = new(StringComparer.Ordinal)
    {
        ["200"] = "OK",
        ["201"] = "Created; `Location` header points to the new resource",
        ["204"] = "No content",
        ["400"] = "Validation failed; `errors` lists the invalid fields",
        ["401"] = "Missing, invalid or expired bearer token",
        ["403"] = "Authenticated but not allowed (role)",
        ["404"] = "Not found, or it belongs to another user",
        ["409"] = "Conflict with the current state (duplicate, in use, already decided)",
        ["422"] = "Business rule violated; `detail` says which",
        ["429"] = "Rate limit or budget reached; see `Retry-After`",
        ["503"] = "A dependency is unavailable; see `Retry-After`",
    };

    private readonly SchemaExamples _synth = new(spec);

    /// <summary>Number of operations without a recorded example.</summary>
    public int Synthesized { get; private set; }

    /// <summary>The Markdown text.</summary>
    public string Render()
    {
        var md = new StringBuilder();
        var operations = Operations().ToList();
        md.AppendLine(CultureInfo.InvariantCulture, $"# {title} reference");
        md.AppendLine();
        md.AppendLine(CultureInfo.InvariantCulture, $"> Generated by `ApiDocsGenerator` from [`{service}.openapi.json`]({service}.openapi.json) and examples recorded against the running service. Do not edit by hand; regenerate with `ONELOAF_EXPORT_DOCS=1 dotnet test tests/OneLoaf.IntegrationTests --filter FullyQualifiedName~ApiDocsGenerator`.");
        md.AppendLine();
        md.AppendLine(CultureInfo.InvariantCulture, $"**Base URL:** {baseUrls}  ");
        md.AppendLine("**Version:** `v1` (in the path) · **Format:** JSON, camelCase, enums as snake_case strings, times ISO 8601 with offset  ");
        md.AppendLine("**Errors:** RFC 9457 problem details — see [error taxonomy](../guides/errors.md). **Auth:** see [authentication](../guides/authentication.md).");
        md.AppendLine();
        md.AppendLine(CultureInfo.InvariantCulture, $"{operations.Count} operations.");
        md.AppendLine();

        var byTag = operations.GroupBy(o => o.Tag).ToList();
        md.AppendLine("## Contents");
        md.AppendLine();
        foreach (var group in byTag)
        {
            md.AppendLine(CultureInfo.InvariantCulture, $"- [{group.Key}](#{Anchor(group.Key)})");
            foreach (var op in group)
            {
                md.AppendLine(CultureInfo.InvariantCulture, $"  - [`{op.Method.ToUpperInvariant()} {op.Path}`](#{Anchor(op.Id)}) — {op.Summary}");
            }
        }

        md.AppendLine("- [Data models](#data-models)");
        md.AppendLine();

        foreach (var group in byTag)
        {
            md.AppendLine(CultureInfo.InvariantCulture, $"## {group.Key}");
            md.AppendLine();
            foreach (var op in group)
            {
                RenderOperation(md, op);
            }
        }

        RenderModels(md);
        return md.ToString().ReplaceLineEndings("\n");
    }

    private void RenderOperation(StringBuilder md, Operation op)
    {
        md.AppendLine(CultureInfo.InvariantCulture, $"<a id=\"{Anchor(op.Id)}\"></a>");
        md.AppendLine(CultureInfo.InvariantCulture, $"### {op.Summary}");
        md.AppendLine();
        md.AppendLine(CultureInfo.InvariantCulture, $"`{op.Method.ToUpperInvariant()} {op.Path}` · operation id `{op.Id}` · auth: {Auth(op.Node)}");
        md.AppendLine();
        if (op.Node["description"]?.GetValue<string>() is { Length: > 0 } description)
        {
            md.AppendLine(description);
            md.AppendLine();
        }

        if (op.Node["parameters"] is JsonArray { Count: > 0 } parameters)
        {
            md.AppendLine("| Parameter | In | Type | Required | Description |");
            md.AppendLine("|---|---|---|---|---|");
            foreach (var p in parameters.OfType<JsonObject>())
            {
                md.AppendLine(CultureInfo.InvariantCulture,
                    $"| `{Camel(p["name"]!.GetValue<string>())}` | {p["in"]} | {TypeOf(p["schema"])}{Default(p["schema"])} | {(p["required"]?.GetValue<bool>() == true ? "yes" : "no")} | {Cell(p["description"]?.GetValue<string>())} |");
            }

            md.AppendLine();
        }

        var body = op.Node["requestBody"]?["content"]?["application/json"]?["schema"];
        if (body is not null)
        {
            md.AppendLine(CultureInfo.InvariantCulture, $"**Request body:** {TypeOf(body)}");
            md.AppendLine();
        }

        md.AppendLine("| Status | Meaning | Body |");
        md.AppendLine("|---|---|---|");
        if (op.Node["responses"] is JsonObject responses)
        {
            foreach (var (status, response) in responses.OrderBy(r => r.Key, StringComparer.Ordinal))
            {
                var content = response?["content"] as JsonObject;
                var schema = content?.FirstOrDefault().Value?["schema"];
                var media = content?.FirstOrDefault().Key;
                var bodyText = schema is null ? (media is null ? "—" : $"`{media}`") : TypeOf(schema);
                md.AppendLine(CultureInfo.InvariantCulture, $"| {status} | {StatusMeaning.GetValueOrDefault(status, response?["description"]?.GetValue<string>() ?? string.Empty)} | {bodyText} |");
            }
        }

        md.AppendLine();
        if (examples.TryGetValue(op.Id, out var recorded) && recorded.Count > 0)
        {
            foreach (var exchange in recorded.DistinctBy(e => e.Case))
            {
                RenderExchange(md, exchange);
            }
        }
        else
        {
            Synthesized++;
            RenderSynthesized(md, op, body);
        }
    }

    private static void RenderExchange(StringBuilder md, RecordedExchange e)
    {
        md.AppendLine(CultureInfo.InvariantCulture, $"<details><summary>Example — {e.Case} ({e.Status})</summary>");
        md.AppendLine();
        md.AppendLine("```http");
        md.AppendLine(CultureInfo.InvariantCulture, $"{e.Method} {e.Path}");
        if (e.Authenticated)
        {
            md.AppendLine("Authorization: Bearer <access token>");
        }

        if (e.RequestBody is not null)
        {
            md.AppendLine("Content-Type: application/json");
            md.AppendLine();
            md.AppendLine(Json(e.RequestBody));
        }

        md.AppendLine("```");
        md.AppendLine();
        md.AppendLine(CultureInfo.InvariantCulture, $"Response `{e.Status}`{(e.ResponseContentType is null ? string.Empty : $" `{e.ResponseContentType}`")}:");
        md.AppendLine();
        if (e.ResponseBody is null)
        {
            md.AppendLine("_(no body)_");
        }
        else if (e.ResponseBody is JsonValue text && e.ResponseContentType?.Contains("json", StringComparison.Ordinal) != true)
        {
            md.AppendLine("```text");
            md.AppendLine(string.Join('\n', text.GetValue<string>().TrimStart('﻿').Split('\n').Take(6)).TrimEnd());
            md.AppendLine("```");
        }
        else
        {
            md.AppendLine("```json");
            md.AppendLine(Json(Shorten(e.ResponseBody.DeepClone())));
            md.AppendLine("```");
        }

        md.AppendLine();
        md.AppendLine("</details>");
        md.AppendLine();
    }

    private void RenderSynthesized(StringBuilder md, Operation op, JsonNode? body)
    {
        md.AppendLine("<details><summary>Example — generated from the schema</summary>");
        md.AppendLine();
        md.AppendLine("```http");
        md.AppendLine(CultureInfo.InvariantCulture, $"{op.Method.ToUpperInvariant()} {op.Path}");
        if (op.Node["security"] is not null)
        {
            md.AppendLine("Authorization: Bearer <access token>");
        }

        if (body is not null)
        {
            md.AppendLine("Content-Type: application/json");
            md.AppendLine();
            md.AppendLine(Json(_synth.For(body)));
        }

        md.AppendLine("```");
        var success = (op.Node["responses"] as JsonObject)?.FirstOrDefault(r => r.Key.StartsWith('2'));
        var schema = (success?.Value?["content"] as JsonObject)?.FirstOrDefault().Value?["schema"];
        if (schema is not null)
        {
            md.AppendLine();
            md.AppendLine(CultureInfo.InvariantCulture, $"Response `{success!.Value.Key}`:");
            md.AppendLine();
            md.AppendLine("```json");
            md.AppendLine(Json(_synth.For(schema)));
            md.AppendLine("```");
        }

        md.AppendLine();
        md.AppendLine("</details>");
        md.AppendLine();
    }

    private void RenderModels(StringBuilder md)
    {
        md.AppendLine("## Data models");
        md.AppendLine();
        if (spec["components"]?["schemas"] is not JsonObject schemas)
        {
            return;
        }

        foreach (var (name, schema) in schemas.OrderBy(s => s.Key, StringComparer.Ordinal))
        {
            md.AppendLine(CultureInfo.InvariantCulture, $"<a id=\"{Anchor("model-" + name)}\"></a>");
            md.AppendLine(CultureInfo.InvariantCulture, $"### {name}");
            md.AppendLine();
            if (schema?["description"]?.GetValue<string>() is { Length: > 0 } description)
            {
                md.AppendLine(description);
                md.AppendLine();
            }

            if (schema?["enum"] is JsonArray values)
            {
                md.AppendLine("Values: " + string.Join(", ", values.Select(v => $"`{v}`")));
                md.AppendLine();
                continue;
            }

            if (schema?["properties"] is not JsonObject properties || properties.Count == 0)
            {
                md.AppendLine(CultureInfo.InvariantCulture, $"Type: {TypeOf(schema)}");
                md.AppendLine();
                continue;
            }

            var required = (schema["required"] as JsonArray)?.Select(r => r!.GetValue<string>()).ToHashSet(StringComparer.Ordinal) ?? [];
            md.AppendLine("| Field | Type | Required | Description |");
            md.AppendLine("|---|---|---|---|");
            foreach (var (field, property) in properties)
            {
                md.AppendLine(CultureInfo.InvariantCulture,
                    $"| `{field}` | {TypeOf(property)} | {(required.Contains(field) ? "yes" : "no")} | {Cell(property?["description"]?.GetValue<string>())} |");
            }

            md.AppendLine();
        }
    }

    private IEnumerable<Operation> Operations()
    {
        if (spec["paths"] is not JsonObject paths)
        {
            yield break;
        }

        foreach (var (path, item) in paths)
        {
            foreach (var method in Methods)
            {
                if (item?[method] is JsonObject node)
                {
                    yield return new Operation(
                        (node["tags"] as JsonArray)?.FirstOrDefault()?.GetValue<string>() ?? "Other",
                        method, path, node["operationId"]?.GetValue<string>() ?? $"{method}{path}",
                        node["summary"]?.GetValue<string>() ?? path, node);
                }
            }
        }
    }

    private string TypeOf(JsonNode? schema)
    {
        if (schema is null)
        {
            return "—";
        }

        if (schema["$ref"]?.GetValue<string>() is { } reference)
        {
            var name = reference[(reference.LastIndexOf('/') + 1)..];
            return $"[{name}](#{Anchor("model-" + name)})";
        }

        var nullable = schema["type"] is JsonArray types && types.Any(t => t?.GetValue<string>() == "null");
        var type = SchemaExamples.MainType(schema);
        var text = type switch
        {
            "array" => $"array of {TypeOf(schema["items"])}",
            "object" when schema["additionalProperties"] is JsonNode additional => $"map of {TypeOf(additional)}",
            null when schema["oneOf"] is JsonArray oneOf => string.Join(" or ", oneOf.Select(TypeOf)),
            null => "any",
            _ => schema["format"]?.GetValue<string>() is { } format ? $"{type} ({format})" : type,
        };
        if (schema["enum"] is JsonArray values)
        {
            text += ": " + string.Join(" \\| ", values.Where(v => v is not null).Select(v => $"`{v}`"));
        }

        return nullable ? text + ", nullable" : text;
    }

    private static string Default(JsonNode? schema) =>
        schema?["default"] is JsonNode value ? $", default `{value.ToJsonString()}`" : string.Empty;

    private static string Auth(JsonNode operation)
    {
        if (operation["security"] is null)
        {
            return "none";
        }

        return operation["description"]?.GetValue<string>()?.Contains("Requires the admin role", StringComparison.Ordinal) == true
            ? "bearer token, role `admin`"
            : "bearer token";
    }

    private static JsonNode? Shorten(JsonNode? node)
    {
        switch (node)
        {
            case JsonArray array:
                while (array.Count > MaxArrayItems)
                {
                    array.RemoveAt(array.Count - 1);
                }

                foreach (var item in array)
                {
                    Shorten(item);
                }

                break;
            case JsonObject obj:
                foreach (var (key, value) in obj.ToList())
                {
                    if (key == "accessToken" && value is JsonValue)
                    {
                        obj[key] = "eyJhbGciOiJSUzI1NiIs...";
                    }
                    else
                    {
                        Shorten(value);
                    }
                }

                break;
        }

        return node;
    }

    private static string Json(JsonNode? node) => node is null ? "null" : node.ToJsonString(Indented).ReplaceLineEndings("\n");

    private static string Camel(string name) => name.Length == 0 ? name : char.ToLowerInvariant(name[0]) + name[1..];

    private static string Cell(string? text) => string.IsNullOrEmpty(text) ? string.Empty : text.Replace("|", "\\|", StringComparison.Ordinal);

    private static string Anchor(string text) => text.ToLowerInvariant().Replace(' ', '-');

    private sealed record Operation(string Tag, string Method, string Path, string Id, string Summary, JsonNode Node);
}
