namespace OneLoaf.Web.Shared.Ui;

/// <summary>Button variants (<c>.ol-btn--…</c>).</summary>
public enum ButtonVariant
{
    /// <summary>The one main action of a view.</summary>
    Primary,

    /// <summary>Outlined secondary action.</summary>
    Secondary,

    /// <summary>Text-only action.</summary>
    Ghost,

    /// <summary>Destructive action (always confirmed).</summary>
    Danger,
}
