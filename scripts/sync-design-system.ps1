<#
.SYNOPSIS
    Copies the OneLoaf design system into the web client and regenerates the icon set.

.DESCRIPTION
    The single source of the design system is docs/frontend/design-system. This script:
      1. copies tokens.css and components.css to src/Web/OneLoaf.Web/wwwroot/css;
      2. copies icons/*.svg and logos/*.svg to wwwroot/icons and wwwroot/logos;
      3. generates IconName.g.cs and IconPaths.g.cs in src/Web/OneLoaf.Web.Shared/Ui/Icons, so that OlIcon renders
         inline SVG that inherits currentColor (no <img> requests).
    Run it after any change in docs/frontend/design-system and commit the result. CI fails when the copies differ.

.PARAMETER Check
    Only verify that the copies are up to date; exit 1 when they are not (used by CI).

.EXAMPLE
    pwsh scripts/sync-design-system.ps1
    pwsh scripts/sync-design-system.ps1 -Check
#>
[CmdletBinding()]
param([switch] $Check)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

$root = Split-Path -Parent $PSScriptRoot
$source = Join-Path $root 'docs/frontend/design-system'
$wwwroot = Join-Path $root 'src/Web/OneLoaf.Web/wwwroot'
$iconCode = Join-Path $root 'src/Web/OneLoaf.Web.Shared/Ui/Icons'
$utf8 = [System.Text.UTF8Encoding]::new($false)

# Desired content of every target file: path -> text. Built first, then written or compared.
$targets = [ordered]@{}

# Ordinal sort by base name: Sort-Object is culture-sensitive and orders "check" / "check-circle" differently on
# Windows and Linux, which would make the generated enum differ between machines.
function Get-SortedSvg([string] $directory) {
    $files = [System.IO.FileInfo[]]@(Get-ChildItem $directory -Filter '*.svg')
    $keys = [string[]]@($files | ForEach-Object { $_.BaseName })
    [Array]::Sort($keys, $files, [StringComparer]::Ordinal)
    return $files
}

function Read-Text([string] $path) {
    ([System.IO.File]::ReadAllText($path, $utf8)) -replace "`r`n", "`n"
}

foreach ($css in 'tokens.css', 'components.css') {
    $targets[(Join-Path $wwwroot "css/$css")] = Read-Text (Join-Path $source $css)
}

foreach ($folder in 'icons', 'logos') {
    foreach ($svg in Get-SortedSvg (Join-Path $source $folder)) {
        $targets[(Join-Path $wwwroot "$folder/$($svg.Name)")] = Read-Text $svg.FullName
    }
}

function ConvertTo-PascalCase([string] $kebab) {
    (($kebab -split '-') | ForEach-Object { $_.Substring(0, 1).ToUpperInvariant() + $_.Substring(1) }) -join ''
}

$icons = Get-SortedSvg (Join-Path $source 'icons')
$enumMembers = [System.Text.StringBuilder]::new()
$switchArms = [System.Text.StringBuilder]::new()
foreach ($icon in $icons) {
    $name = ConvertTo-PascalCase $icon.BaseName
    $svg = Read-Text $icon.FullName
    if ($svg -notmatch '(?s)<svg[^>]*>(?<inner>.*)</svg>') { throw "Not an SVG: $($icon.FullName)" }
    # Inner markup only: stroke, fill and size come from the .ol-icon class, so the icon follows currentColor.
    $inner = $Matches['inner'].Trim()
    [void]$enumMembers.AppendLine("    /// <summary>icons/$($icon.Name)</summary>")
    [void]$enumMembers.AppendLine("    $name,")
    [void]$switchArms.AppendLine("        IconName.$name => `"`"`"$inner`"`"`",")
}

$header = "// <auto-generated>Generated by scripts/sync-design-system.ps1 from docs/frontend/design-system/icons. Do not edit.</auto-generated>"
$targets[(Join-Path $iconCode 'IconName.g.cs')] = @"
$header
namespace OneLoaf.Web.Shared.Ui.Icons;

/// <summary>Icons of the OneLoaf design system.</summary>
public enum IconName
{
$($enumMembers.ToString().TrimEnd())
}

"@ -replace "`r`n", "`n"

$targets[(Join-Path $iconCode 'IconPaths.g.cs')] = @"
$header
namespace OneLoaf.Web.Shared.Ui.Icons;

/// <summary>Inner SVG markup (24 x 24 view box) of every icon.</summary>
internal static class IconPaths
{
    /// <summary>Returns the inner markup of the icon.</summary>
    public static string Get(IconName name) => name switch
    {
$($switchArms.ToString().TrimEnd())
        _ => throw new ArgumentOutOfRangeException(nameof(name), name, "Unknown icon."),
    };
}

"@ -replace "`r`n", "`n"

$stale = @()
foreach ($path in $targets.Keys) {
    $wanted = $targets[$path]
    $current = if (Test-Path $path) { Read-Text $path } else { $null }
    if ($current -ceq $wanted) { continue }
    $stale += $path
    if (-not $Check) {
        New-Item -ItemType Directory -Force -Path (Split-Path -Parent $path) | Out-Null
        [System.IO.File]::WriteAllText($path, $wanted, $utf8)
    }
}

if ($Check) {
    if ($stale.Count -gt 0) {
        Write-Error ("Design system copies are out of date. Run scripts/sync-design-system.ps1:`n" + ($stale -join "`n"))
    }
    Write-Host 'Design system copies are up to date.'
}
else {
    Write-Host "Design system synced: $($stale.Count) file(s) written, $($targets.Count - $stale.Count) unchanged."
}
