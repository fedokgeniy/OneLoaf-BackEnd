ON_DELETE = {"a": "NO ACTION", "r": "RESTRICT", "c": "CASCADE", "n": "SET NULL", "d": "SET DEFAULT"}
KIND = {"f": "function", "p": "procedure"}


def q(sql: str):
    out = subprocess.run(["psql", "-X", "-tA", "-F", "\t", "-v", "ON_ERROR_STOP=1", "-c", sql],
                         check=True, capture_output=True, text=True).stdout
    return [line.split("\t") for line in out.splitlines() if line]


def esc(s: str) -> str:
    return s.replace("|", "\\|")


def main():
    base_tables = {r[0] for r in q("SELECT relname FROM pg_class WHERE relnamespace = 'public'::regnamespace AND relkind = 'r'")}
    known = {t for t, _, _ in TABLES}
    missing = base_tables - known - {"__ef_migrations_history"}
    if missing:
        raise SystemExit(f"Tables without description: {sorted(missing)}")

    cols = defaultdict(list)
    for t, c, typ, notnull, default in q("""
        SELECT c.relname, a.attname, format_type(a.atttypid, a.atttypmod), a.attnotnull,
               coalesce(pg_get_expr(d.adbin, d.adrelid), '')
        FROM pg_attribute a
        JOIN pg_class c ON c.oid = a.attrelid
        LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
        WHERE c.relnamespace = 'public'::regnamespace AND c.relkind IN ('r', 'v', 'm') AND a.attnum > 0 AND NOT a.attisdropped
        ORDER BY c.relname, a.attnum"""):
        cols[t].append((c, typ, notnull == "f", default))

    pk = defaultdict(list)
    for t, c in q("""
        SELECT cl.relname, a.attname FROM pg_constraint con
        JOIN pg_class cl ON cl.oid = con.conrelid
        JOIN LATERAL unnest(con.conkey) WITH ORDINALITY k(attnum, ord) ON true
        JOIN pg_attribute a ON a.attrelid = con.conrelid AND a.attnum = k.attnum
        WHERE con.contype = 'p' AND cl.relnamespace = 'public'::regnamespace ORDER BY cl.relname, k.ord"""):
        pk[t].append(c)

    fks = defaultdict(list)
    fk_cols = defaultdict(dict)
    for t, name, col, ref_t, ref_c, deltype, deferrable in q("""
        SELECT cl.relname, con.conname, a.attname, rcl.relname, ra.attname, con.confdeltype, con.condeferrable
        FROM pg_constraint con
        JOIN pg_class cl ON cl.oid = con.conrelid
        JOIN pg_class rcl ON rcl.oid = con.confrelid
        JOIN pg_attribute a ON a.attrelid = con.conrelid AND a.attnum = con.conkey[1]
        JOIN pg_attribute ra ON ra.attrelid = con.confrelid AND ra.attnum = con.confkey[1]
        WHERE con.contype = 'f' AND cl.relnamespace = 'public'::regnamespace ORDER BY cl.relname, con.conname"""):
        rule = ON_DELETE[deltype] + (", DEFERRABLE INITIALLY DEFERRED" if deferrable == "t" else "")
        fks[t].append((name, col, ref_t, ref_c, rule))
        fk_cols[t][col] = f"FK ({ref_t})"

    checks = defaultdict(list)
    for t, name, definition in q("""
        SELECT cl.relname, con.conname, pg_get_constraintdef(con.oid)
        FROM pg_constraint con JOIN pg_class cl ON cl.oid = con.conrelid
        WHERE con.contype = 'c' AND cl.relnamespace = 'public'::regnamespace ORDER BY cl.relname, con.conname"""):
        checks[t].append((name, definition.removeprefix("CHECK ")))

    indexes = defaultdict(list)
    unique_cols = defaultdict(set)
    for t, name, definition, is_unique, is_primary in q("""
        SELECT t.relname, i.relname, pg_get_indexdef(ix.indexrelid), ix.indisunique, ix.indisprimary
        FROM pg_index ix JOIN pg_class i ON i.oid = ix.indexrelid JOIN pg_class t ON t.oid = ix.indrelid
        WHERE t.relnamespace = 'public'::regnamespace ORDER BY t.relname, i.relname"""):
        if is_primary == "t":
            continue
        cols_part = definition[definition.index("(") + 1: definition.rindex(")")]
        where = definition.split(" WHERE ", 1)[1] if " WHERE " in definition else ""
        if where:
            cols_part = definition[definition.index("(") + 1: definition.index(") WHERE")]
        indexes[t].append((name, cols_part, is_unique == "t", where))
        if is_unique == "t" and "," not in cols_part and not where:
            unique_cols[t].add(cols_part.strip())

    triggers = defaultdict(list)
    for t, name, definition, func in q("""
        SELECT c.relname, tg.tgname, pg_get_triggerdef(tg.oid), p.proname
        FROM pg_trigger tg JOIN pg_class c ON c.oid = tg.tgrelid JOIN pg_proc p ON p.oid = tg.tgfoid
        WHERE NOT tg.tgisinternal AND c.relnamespace = 'public'::regnamespace ORDER BY c.relname, tg.tgname"""):
        when = definition.split(" ON ")[0].split(" ", 3)[-1]           # e.g. BEFORE UPDATE OF status
        when = when.replace(name + " ", "")
        triggers[t].append((name, when, FUNC_DESC[func]))

    w = sys.stdout.write
    w("# OneLoaf data dictionary\n\n")
    w("> Generated by `tools/generate_data_dictionary.py` from the schema created by the migrations: types, keys, constraints, "
      "indexes, triggers and reference values are read from the PostgreSQL system catalog.\n\n")
    w(f"**DBMS:** PostgreSQL 16. **Schema:** `public`. **Tables:** {len(TABLES)} "
      "(plus the service table `__ef_migrations_history` with the history of applied migrations). "
      "**Layers:** one transactional (OLTP) layer with views on top of it, see [design.md](design.md#data-layers).\n\n")
    w("## Conventions\n\n")
    w("- Table and column names are `snake_case`. Primary keys are `uuid` with `DEFAULT gen_random_uuid()`; reference tables use a text code.\n")
    w("- Points in time are `timestamp with time zone` (stored in UTC); dates without time are `date`.\n")
    w("- Money and quantities are `numeric(p,s)`: exact decimal arithmetic without `float` rounding errors.\n")
    w("- Classifications with attributes (units, currencies, stage types, categories, flour types) are reference tables with foreign keys. "
      "Closed sets of states the logic depends on (statuses, roles, reminder kinds) are `varchar(32)` with a CHECK `ck_<table>_<column>`.\n")
    w("- JSON (`jsonb`) is used only in three columns with a documented and checked structure: `recipes.variant_overrides`, "
      "`published_recipes.snapshot`, `chat_messages.tool_payload` (see [design.md](design.md#json-columns)).\n")
    w("- Constraint names: `pk_` primary key, `fk_<table>_<referenced>_<column>` foreign key, `ux_` unique index, "
      "`ix_` index, `ck_` CHECK, `trg_` trigger.\n\n")
    w("**Key:** PK - primary key, FK - foreign key (referenced table in brackets), UQ - unique value. "
      "**Data quality:** [C] - guaranteed by a database constraint or trigger, [M] - monitored by the view "
      "`v_data_quality_issues` (the rule depends on time or on several tables and cannot be a constraint).\n\n")

    w("## Tables\n\n| # | Table | Block | Purpose |\n|---|---|---|---|\n")
    for i, (t, block, purpose) in enumerate(TABLES, 1):
        w(f"| {i} | [`{t}`](#{t}) | {block} | {purpose} |\n")
    w("\nOther sections: [reference values](#reference-values), [views](#views), "
      "[functions and procedures](#functions-and-procedures)\n\n")

    for t, block, purpose in TABLES:
        w(f"## {t}\n\n**Block:** {block}. {purpose}\n\n")
        w("**Data quality expectations**\n\n")
        for item in QUALITY[t]:
            w(f"- {item}\n")
        w("\n| Column | Type | Null | Default | Key | Description |\n|---|---|---|---|---|---|\n")
        for c, typ, nullable, default in cols[t]:
            keys = []
            if c in pk[t]:
                keys.append("PK")
            if c in fk_cols[t]:
                keys.append(fk_cols[t][c])
            if c in unique_cols[t]:
                keys.append("UQ")
            desc = DESCRIPTIONS.get(t, {}).get(c) or COMMON.get(c)
            if desc is None:
                raise SystemExit(f"No description for {t}.{c}")
            w(f"| `{c}` | `{typ}` | {'yes' if nullable else 'no'} | {f'`{esc(default)}`' if default else ''} | "
              f"{', '.join(keys)} | {desc} |\n")
        w("\n")
        if len(pk[t]) > 1:
            w(f"Composite primary key: `({', '.join(pk[t])})`.\n\n")
        if fks[t]:
            w("**Foreign keys**\n\n| Constraint | Column | References | ON DELETE |\n|---|---|---|---|\n")
            for name, col, ref_t, ref_c, rule in fks[t]:
                w(f"| `{name}` | `{col}` | `{ref_t}.{ref_c}` | {rule} |\n")
            w("\n")
        if indexes[t]:
            w("**Indexes** (besides the primary key)\n\n| Index | Columns | Unique | Condition |\n|---|---|---|---|\n")
            for name, cols_part, uniq, where in indexes[t]:
                w(f"| `{name}` | `{cols_part}` | {'yes' if uniq else 'no'} | {f'`{esc(where)}`' if where else ''} |\n")
            w("\n")
        if checks[t]:
            w("**CHECK constraints**\n\n| Constraint | Condition |\n|---|---|\n")
            for name, definition in checks[t]:
                w(f"| `{name}` | `{esc(definition)}` |\n")
            w("\n")
        if triggers[t]:
            w("**Triggers**\n\n| Trigger | When | What it does |\n|---|---|---|\n")
            for name, when, desc in triggers[t]:
                w(f"| `{name}` | {when} | {esc(desc)} |\n")
            w("\n")

    w("## Reference values\n\nInserted by the `InitialSchema` migration (EF Core `HasData`, source "
      "`src/OneLoaf.Infrastructure/Persistence/ReferenceData.cs`) and included in `db/schema.sql`.\n\n")
    for t in ["units", "currencies", "stage_types", "ingredient_categories", "flour_types"]:
        names = [c for c, _, _, _ in cols[t]]
        order = "sort_order" if "sort_order" in names else "code"
        rows = q(f"SELECT {', '.join(names)} FROM {t} ORDER BY {order}")
        w(f"### {t}\n\n| {' | '.join(names)} |\n|{'---|' * len(names)}\n")
        for r in rows:
            w("| " + " | ".join({'t': 'yes', 'f': 'no'}.get(v, v) for v in r) + " |\n")
        w("\n")

    w("## Views\n\n")
    for v, kind in q("""
        SELECT c.relname, c.relkind
        FROM pg_class c WHERE c.relnamespace = 'public'::regnamespace AND c.relkind IN ('v', 'm') ORDER BY c.relname"""):
        w(f"### {v}\n\n{'Materialized view. ' if kind == 'm' else ''}{VIEW_DESC[v]}\n\n")
        w("| Column | Type |\n|---|---|\n")
        for c, typ, _, _ in cols[v]:
            w(f"| `{c}` | `{typ}` |\n")
        w("\n")

    w("## Functions and procedures\n\nTrigger functions are listed above in the sections of their tables.\n\n")
    w("| Name | Kind | Arguments | Result | Description |\n|---|---|---|---|---|\n")
    for name, kind, args, result, secdef in q("""
        SELECT p.proname, p.prokind, pg_get_function_identity_arguments(p.oid),
               coalesce(pg_get_function_result(p.oid), ''), p.prosecdef
        FROM pg_proc p
        WHERE p.pronamespace = 'public'::regnamespace AND p.prorettype <> 'trigger'::regtype
        ORDER BY p.prokind, p.proname"""):
        kind_txt = KIND.get(kind, kind) + (", SECURITY DEFINER" if secdef == "t" else "")
        if len(result) > 60:
            result = result.split("(")[0] + "(...)"
        args_txt = f"`{esc(args)}`" if args else "-"
        result_txt = f"`{esc(result)}`" if result else "-"
        w(f"| `{name}` | {kind_txt} | {args_txt} | {result_txt} | {esc(FUNC_DESC[name])} |\n")


if __name__ == "__main__":
    main()
